import java.util.Properties
import java.io.FileInputStream

// Google Maps needs its key in the Android manifest at build time, which
// --dart-define cannot reach. Read it from local.properties (untracked) and
// inject it as a manifest placeholder, so the key stays out of source control.
val localProperties = Properties()
val localPropertiesFile = rootProject.file("local.properties")
if (localPropertiesFile.exists()) {
    FileInputStream(localPropertiesFile).use { localProperties.load(it) }
}
val mapsApiKey: String = localProperties.getProperty("MAPS_API_KEY") ?: ""

